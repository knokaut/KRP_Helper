    def _register_hotkeys(self, fid):
        self.hotkey_map = {}
        for hotkey, entry in self.entries[fid]:
            self.hotkey_map[parse_hotkey(hotkey)] = entry

    def _on_key(self, event):
        if event.event_type != "down" or self._sending: return
        ctrl = keyboard.is_pressed("ctrl")
        alt = keyboard.is_pressed("alt")
        shift = keyboard.is_pressed("shift")

        if ctrl and not alt:
            if event.scan_code == SCAN_MEGAPHONE:
                mega_key = self._faction(self.current_fid)[7]
                if mega_key: self._events.put(("text", self.phrases[mega_key], self.current_fid))
                return
            if event.scan_code == SCAN_TOGGLE_HINTS:
                self._events.put(("toggle", None, self.current_fid))
                return

        mods = frozenset(m for m, on in (("ctrl", ctrl), ("alt", alt), ("shift", shift)) if on)
        entry = self.hotkey_map.get((mods, event.scan_code))
        if entry is not None:
            self._events.put(("entry", entry, self.current_fid))

    def _save_state(self):
        """Сохраняет отредактированные фразы и звания/имена в phrases.json."""
        try:
            for key, items in self.section_entries.items():
                self.phrases[key] = [[label, hotkey, entry.get()] for label, hotkey, entry in items]
            self.phrases["_profiles"] = {
                fid: [v[0].get(), v[1].get()] for fid, v in self.faction_vars.items()
            }
            with open(CONFIG_PATH, "w", encoding="utf-8") as f:
                json.dump(self.phrases, f, ensure_ascii=False, indent=2)
        except Exception:
            pass

    def _on_close(self):
        self._save_state()
        keyboard.unhook_all()
        self.destroy()

    def _poll(self):
        try:
            while True:
                kind, payload, fid = self._events.get_nowait()
                if kind == "toggle":
                    self.hints_var.set(not self.hints_var.get())
                    self._toggle_overlay()
                else:
                    text = payload.get() if kind == "entry" else payload
                    self._dispatch_text(text, fid)
        except queue.Empty: pass
        if self.sent_count != self._shown_count:
            self._shown_count = self.sent_count
            self._refresh_status()
            self.overlay.set_count(self.sent_count)
        self.after(80, self._poll)

    def _refresh_status(self):
        self.status.configure(
            text=(f"{self._faction(self.current_fid)[1]}: F1–F8 · Alt+1–0 · Ctrl+1–0 · "
                  f"Ctrl+Shift+1–0 · Ctrl+Alt+1–0 · Ctrl+F1–F2 · Ctrl+Ж мегафон · Ctrl+Ё подсказки"))
        self.counter_lbl.configure(text=f"Отправлено: {self.sent_count}")

    def _dispatch_text(self, text, fid):
        self._save_state()
        rank_var, name_var = self.faction_vars[fid]
        text = text.replace("{rank}", rank_var.get()).replace("{name}", name_var.get())
        threading.Thread(target=self._send_worker, args=(text,), daemon=True).start()

    @staticmethod
    def _chord(*scans):
        for sc in scans: keyboard.press(sc)
        for sc in reversed(scans): keyboard.release(sc)

    def _send_worker(self, text):
        with self._lock:
            now = time.time()
            if now - self._last_send < COOLDOWN: return
            self._last_send = now
            self._sending = True
            try:
                old_clip = None
                try: old_clip = pyperclip.paste()
                except Exception: pass

                pyperclip.copy(text)
                for mod in ("alt", "ctrl", "shift"): keyboard.release(mod)
                time.sleep(SEND_DELAY)
                keyboard.send(CHAT_SCAN)
                time.sleep(SEND_DELAY)
                self._chord(SCAN_CTRL, SCAN_A)
                self._chord(SCAN_CTRL, SCAN_V)
                time.sleep(SEND_DELAY)
                keyboard.send(SCAN_ENTER)

                if old_clip is not None:
                    time.sleep(SEND_DELAY)
                    try: pyperclip.copy(old_clip)
                    except Exception: pass
                self.sent_count += 1
            finally:
                time.sleep(0.25)
                self._sending = False

