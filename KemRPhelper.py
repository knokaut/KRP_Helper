def load_phrases():
    data = {}
    if os.path.exists(CONFIG_PATH):
        try:
            with open(CONFIG_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            pass
    changed = False
    for key, value in DEFAULT.items():
        if key not in data:
            data[key] = value
            changed = True
    if data.get("_version", 0) < DATA_VERSION:
        for key, value in DEFAULT.items():
            if isinstance(value, list) and isinstance(data.get(key), list):
                have = {row[1] for row in data[key]}
                data[key].extend(row for row in value if row[1] not in have)
        if data.get("_version", 0) < 26:
            data["opg"] = DEFAULT["opg"]
        # Очистка устаревших неиспользуемых ключей УСБ
        for old_key in ("usb_proc", "usb_arrest", "usb_uk", "usb_disc"):
            if old_key in data:
                del data[old_key]
        data["_version"] = DATA_VERSION
        changed = True
    if changed or not os.path.exists(CONFIG_PATH):
        try:
            with open(CONFIG_PATH, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
        except Exception:
            pass
    return data

