def key_scan(key):
    key = key.lower()
    if key in DIGIT_SCAN: return DIGIT_SCAN[key]
    m = re.fullmatch(r"f(\d{1,2})", key)
    if m:
        n = int(m.group(1))
        if 1 <= n <= 10: return 58 + n
        if n in (11, 12): return 76 + n
    return keyboard.key_to_scan_codes(key)[0]

def parse_hotkey(hotkey):
    parts = hotkey.lower().replace(" ", "").split("+")
    return frozenset(parts[:-1]), key_scan(parts[-1])

