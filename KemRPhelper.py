class Splash(ctk.CTkToplevel):
    FADE_IN, FADE_OUT = 0.35, 0.45
    def __init__(self, master, on_done):
        super().__init__(master)
        self._on_done = on_done
        self.overrideredirect(True)
        self.attributes("-topmost", True)
        self.attributes("-alpha", 0.0)
        try:
            self.configure(fg_color="#010101")
            self.attributes("-transparentcolor", "#010101")
        except Exception: pass

        w, h = 500, 280
        x = (self.winfo_screenwidth() - w) // 2
        y = (self.winfo_screenheight() - h) // 2 - 40
        self.geometry(f"{w}x{h}+{x}+{y}")

        box = ctk.CTkFrame(self, corner_radius=24, fg_color="#1E293B", border_width=3, border_color=GOLD)
        box.pack(fill="both", expand=True)
        self._img = icon_ctk(104)
        ctk.CTkLabel(box, image=self._img, text="").pack(pady=(26, 8))
        ctk.CTkLabel(box, text=SPLASH_TEXT, font=("Segoe UI", 22, "bold"), text_color=WHITE).pack()
        ctk.CTkLabel(box, text=f"ver. - {APP_VERSION}", font=("Segoe UI", 12), text_color=WHITE).pack(pady=(2, 14))
        self.bar = ctk.CTkProgressBar(box, width=320, height=6, corner_radius=3, progress_color=GOLD, fg_color="#0F172A")
        self.bar.set(0)
        self.bar.pack()

        self._t0 = time.time()
        self.after(10, self._tick)

    def _tick(self):
        t = time.time() - self._t0
        if t >= SPLASH_SECONDS:
            self.destroy()
            self._on_done()
            return
        if t < SPLASH_SECONDS - self.FADE_OUT: alpha = min(1.0, t / self.FADE_IN)
        else: alpha = max(0.0, (SPLASH_SECONDS - t) / self.FADE_OUT)
        self.attributes("-alpha", alpha)
        self.bar.set(min(1.0, t / (SPLASH_SECONDS - self.FADE_OUT)))
        self.after(20, self._tick)

